func TestTranslateTypes(t *testing.T) {
	src := `Project {
  database_type: 'MySQL'
}
Table t {
  id "int unsigned" [pk, increment]
  flag tinyint(1) [default: 1]
  n mediumint
  name varchar(80) [not null, default: 'x']
  body longtext
  at datetime(6) [default: ` + "`CURRENT_TIMESTAMP(6)`" + `]
  doc json
  bin longblob
  amount decimal(10,2)
  ratio double
  y year
  code char(36) [unique]
  big "bigint unsigned"
  c "int(11)"
  checks {
    ` + "`ratio REGEXP '^[0-9]'`" + `
  }
}
`
	db, d := dbml.Parse(src)
	if db == nil {
		t.Fatal(d)
	}
	if export.SourceDialectOf(db) != export.MySQL {
		t.Fatal("source dialect not read from Project")
	}
	res, err := export.SQLWith(db, export.Postgres, export.Options{TranslateTypes: true})
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range []string{`"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`, `"flag" boolean DEFAULT true`, `"n" integer`,
		`"body" text`, `"at" timestamp(6) DEFAULT (now())`, `"doc" json`, `"bin" bytea`, `"amount" numeric(10,2)`,
		`"ratio" double precision`, `"y" smallint`, `"big" numeric(20)`, `"c" integer`, `CHECK (ratio ~ '^[0-9]')`} {
		if !strings.Contains(res.SQL, w) {
			t.Errorf("postgres: missing %q in\n%s", w, res.SQL)
		}
	}
	ms, _ := export.SQLWith(db, export.MSSQL, export.Options{TranslateTypes: true})
	for _, w := range []string{"[flag] bit DEFAULT (1)", "[body] nvarchar(max)", "[at] datetime2(6) DEFAULT (getdate())", "[code] nchar(36) UNIQUE"} {
		if !strings.Contains(ms.SQL, w) {
			t.Errorf("mssql: missing %q in\n%s", w, ms.SQL)
		}
	}
	// off by default, and SQL is unchanged
	plain, _ := export.SQL(db, export.Postgres)
	if !strings.Contains(plain, `"flag" tinyint(1)`) {
		t.Errorf("SQL translated without the option:\n%s", plain)
	}
}

func TestTranslateFromPostgres(t *testing.T) {
	src := `Project {
  database_type: 'PostgreSQL'
}
Table u {
  id serial [pk]
  uid uuid [default: ` + "`gen_random_uuid()`" + `]
  tags "text[]"
  at timestamptz [default: ` + "`now()`" + `]
  data jsonb
  ip inet
  name text [unique]
  meta text [default: ` + "`'{}'::text`" + `]
  odd "geography(POINT)"
}
Table p {
  id int [pk]
  u_id bigint [ref: > u.id]
  nk int [ref: > u.ip]
}
`
	db, d := dbml.Parse(src)
	if db == nil {
		t.Fatal(d)
	}
	res, err := export.SQLWith(db, export.MySQL, export.Options{TranslateTypes: true})
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range []string{"`id` int PRIMARY KEY AUTO_INCREMENT", "`uid` char(36) DEFAULT (uuid())", "`tags` json", "`at` datetime DEFAULT (CURRENT_TIMESTAMP)",
		"`data` json", "`ip` varchar(43)", "`name` varchar(255) UNIQUE", "`meta` longtext DEFAULT '{}'", "`u_id` int"} {
		if !strings.Contains(res.SQL, w) {
			t.Errorf("mysql: missing %q in\n%s", w, res.SQL)
		}
	}
	if len(res.Warnings) == 0 || !strings.Contains(strings.Join(res.Warnings, "\n"), "geography") {
		t.Errorf("no warning for the unknown type: %v", res.Warnings)
	}
	// PostgreSQL needs a key on the referenced columns: the ref to u.ip is dropped
	pgdb, _ := dbml.Parse(strings.Replace(src, "'PostgreSQL'", "'MySQL'", 1))
	pg, _ := export.SQLWith(pgdb, export.Postgres, export.Options{TranslateTypes: true})
	if strings.Contains(pg.SQL, `REFERENCES "u" ("ip")`) {
		t.Errorf("non-unique reference kept:\n%s", pg.SQL)
	}
}

// tinyint(1) becomes a boolean only when nothing treats it as a number.
func TestTranslateTinyintBool(t *testing.T) {
	src := "Project {\n  database_type: 'MySQL'\n}\nTable t {\n  level tinyint(1) [not null, default: 7]\n  flag tinyint(1) [default: 1]\n  lvl2 tinyint(1) [default: 0]\n  checks {\n    `lvl2 BETWEEN 0 AND 9`\n  }\n}\n"
	db, d := dbml.Parse(src)
	if db == nil {
		t.Fatal(d)
	}
	for _, dl := range []export.Dialect{export.Postgres, export.MSSQL} {
		res, err := export.SQLWith(db, dl, export.Options{TranslateTypes: true})
		if err != nil {
			t.Fatal(err)
		}
		w := strings.Join(res.Warnings, "\n")
		if dl == export.Postgres {
			for _, want := range []string{`"level" smallint NOT NULL DEFAULT 7`, `"flag" boolean DEFAULT true`, `"lvl2" smallint DEFAULT 0`} {
				if !strings.Contains(res.SQL, want) {
					t.Errorf("%s: missing %q in\n%s", dl, want, res.SQL)
				}
			}
		} else if !strings.Contains(res.SQL, "[level] smallint NOT NULL DEFAULT (7)") || !strings.Contains(res.SQL, "[flag] bit DEFAULT (1)") {
			t.Errorf("%s:\n%s", dl, res.SQL)
		}
		if !strings.Contains(w, "column t.level: tinyint(1) kept numeric (default 7)") || !strings.Contains(w, "column t.lvl2: tinyint(1) kept numeric (used numerically in a CHECK)") {
			t.Errorf("%s warnings: %v", dl, res.Warnings)
		}
	}
}

// Every lossy or semantic mapping is reported with table.column.
func TestTranslateWarnings(t *testing.T) {
	src := "Project {\n  database_type: 'MySQL'\n}\nEnum e {\n  a\n  b\n}\nTable t {\n  id int [pk]\n  s \"set('x','y')\"\n  y year\n  u \"int unsigned\"\n  du \"decimal(10,2) unsigned\"\n  j json\n  ts \"datetime(6)\"\n  e e\n  k text [unique]\n  g int [generated: 'id + 1']\n  h int\n  indexes {\n    h [type: hash]\n  }\n}\n"
	db, d := dbml.Parse(src)
	if db == nil {
		t.Fatal(d)
	}
	pg, _ := export.SQLWith(db, export.Postgres, export.Options{TranslateTypes: true})
	ms, _ := export.SQLWith(db, export.MSSQL, export.Options{TranslateTypes: true})
	for dl, cases := range map[*export.Result][]string{
		pg: {"column t.s: set('x','y'): SET values become free text", "column t.y: year: YEAR becomes smallint", "column t.u: int unsigned: unsigned dropped, widened to bigint",
			"column t.du: decimal(10,2) unsigned: unsigned dropped"},
		ms: {"column t.j: json: JSON stored as nvarchar(max)", "column t.e: enum e becomes nvarchar(255) with a CHECK constraint",
			"column t.k: text: length bounded to nvarchar(450)", "index on t: method hash dropped"},
	} {
		w := strings.Join(dl.Warnings, "\n")
		for _, c := range cases {
			if !strings.Contains(w, c) {
				t.Errorf("missing warning %q in\n%s", c, w)
			}
		}
	}
	// PostgreSQL source to MySQL: time zones, casts, json operators
	pgsrc := "Project {\n  database_type: 'PostgreSQL'\n}\nTable p {\n  id int [pk]\n  at timestamptz\n  d jsonb\n  name text [check: `name <> ''::text`]\n  x text [generated: 'd->>\\'a\\'']\n}\n"
	db2, _ := dbml.Parse(pgsrc)
	my, _ := export.SQLWith(db2, export.MySQL, export.Options{TranslateTypes: true})
	w := strings.Join(my.Warnings, "\n")
	for _, c := range []string{"column p.at: timestamptz: time zone dropped", "column p.d: jsonb: jsonb becomes json", "PostgreSQL casts removed", "generated column p.x", "dropped (PostgreSQL-only operator)"} {
		if !strings.Contains(w, c) {
			t.Errorf("missing warning %q in\n%s", c, w)
		}
	}
}

// Booleans used in CHECKs only as booleans stay booleans (Holistics
// mysql_importer checks.in.sql, MySQL -> PostgreSQL).
func TestTranslateBoolInChecks(t *testing.T) {
	b, err := os.ReadFile("../testdata/holistics/dbml-core/importer/mysql_importer/input/checks.in.sql")
	if err != nil {
		t.Fatal(err)
	}
	r, err := importer.ImportWith(string(b), importer.MySQL, importer.ImportOptions{})
	if err != nil || r.Database == nil {
		t.Fatal(err)
	}
	res, err := export.SQLWith(r.Database, export.Postgres, export.Options{TranslateTypes: true})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`"cancelled" boolean`, `"is_enabled" boolean`, `"is_premium" boolean`} {
		if !strings.Contains(res.SQL, want) {
			t.Errorf("missing %q in\n%s", want, res.SQL)
		}
	}
	if strings.Contains(strings.Join(res.Warnings, "\n"), "cancelled: BOOLEAN kept numeric") {
		t.Errorf("warnings: %v", res.Warnings)
	}
	// numeric uses still keep the number
	db, _ := dbml.Parse("Project {\n  database_type: 'MySQL'\n}\nTable t {\n  a boolean [check: `a BETWEEN 0 AND 1`]\n  b boolean [check: `b = TRUE OR b IS NULL`]\n  c boolean [check: `c + 1 > 0`]\n  d boolean [check: `NOT d`]\n}\n")
	res, _ = export.SQLWith(db, export.Postgres, export.Options{TranslateTypes: true})
	for _, want := range []string{`"a" smallint`, `"b" boolean`, `"c" smallint`, `"d" boolean`} {
		if !strings.Contains(res.SQL, want) {
			t.Errorf("missing %q in\n%s", want, res.SQL)
		}
	}
}
