var plainWord = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// IsMySQLReserved reports whether w is a MySQL / MariaDB reserved word.
func IsMySQLReserved(w string) bool { return mysqlReserved[strings.ToUpper(w)] }

// mysqlQuoteReserved rewrites "w" in a fragment, where w is a reserved
// word, to `w`: standard SQL (and go-dbml's clean imports) quote such
// column names with "…", which MySQL reads as a string unless ANSI_QUOTES
// is set. Other "…" tokens are left alone (they may be MySQL strings).
func mysqlQuoteReserved(e string) string {
	if strings.IndexByte(e, '"') < 0 {
		return e
	}
	var b strings.Builder
	for i := 0; i < len(e); i++ {
		c := e[i]
		switch c {
		case '\'', '`':
			j := scanQuoted(e, i, c, c == '\'')
			if j < 0 {
				b.WriteString(e[i:])
				return b.String()
			}
			b.WriteString(e[i : j+1])
			i = j
		case '"':
			j := scanQuoted(e, i, '"', true)
			if j < 0 {
				b.WriteString(e[i:])
				return b.String()
			}
			if w := e[i+1 : j]; plainWord.MatchString(w) && IsMySQLReserved(w) {
				b.WriteString("`" + w + "`")
			} else {
				b.WriteString(e[i : j+1])
			}
			i = j
		default:
			b.WriteByte(c)
		}
	}
	return b.String()
}
