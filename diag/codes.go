// go-dbml specific codes (9000+). These have no @dbml/parse equivalent; they
// guard resource usage on untrusted input.
const (
	// NESTING_TOO_DEEP: brackets/blocks/operators nested beyond MaxDepth.
	NESTING_TOO_DEEP Code = 9000 + iota
	// TOO_MANY_DIAGNOSTICS: the diagnostic cap was reached; later ones were dropped.
	TOO_MANY_DIAGNOSTICS
	// INPUT_TOO_LARGE: a source file exceeds MaxBytes.
	INPUT_TOO_LARGE
	// TOO_MANY_FILES: a project imports more than MaxFiles files.
	TOO_MANY_FILES
	// INTERNAL_ERROR: an unexpected panic inside go-dbml (a bug); the
	// compile result is otherwise empty.
	INTERNAL_ERROR
	// RECORDS_TOO_LARGE: Records blocks exceed MaxRecordRows / MaxRecordBytes.
	RECORDS_TOO_LARGE
	// TOO_MANY_TOKENS: a file has more tokens than MaxTokens; the rest was
	// not parsed.
	TOO_MANY_TOKENS
	// TOO_MANY_ELEMENTS: a block or list has more than MaxElements
	// elements; the rest was skipped.
	TOO_MANY_ELEMENTS
	// CANCELED: the compile was canceled (Options.Cancel / context); no
	// model is returned.
	CANCELED
)

